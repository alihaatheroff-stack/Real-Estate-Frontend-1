export function getMember(id: string) {
  return NETWORK_MEMBERS.find((member) => member.id === id)
}

export function getCurrentMember() {
  return NETWORK_MEMBERS.find((member) => member.id === CURRENT_MEMBER_ID) ?? NETWORK_MEMBERS[0]
}

export function getFollowing(member: NetworkMember) {
  return member.friendIds
    .map((id) => getMember(id))
    .filter((item): item is NetworkMember => item != null)
}

export function getFollowers(memberId: string) {
  return NETWORK_MEMBERS.filter((member) => member.id !== memberId && member.friendIds.includes(memberId))
}
