export function countryToVoteRegion(country: string) {
  if (country === 'Mexico') return 'mexico'
  if (country === 'United States') return 'united-states'
  if (country === 'Canada') return 'canada'
  if (CENTRAL_AMERICA.has(country)) return 'central-america'
  if (CARIBBEAN.has(country)) return 'caribbean'
  return country.toLowerCase().replace(/[^a-z0-9]+/g, '-')
}

